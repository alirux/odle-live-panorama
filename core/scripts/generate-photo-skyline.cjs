/* Rebuild after replacing the source panoramas. Requires @napi-rs/canvas. */
const {createCanvas,loadImage} = require('@napi-rs/canvas');
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const root = path.resolve(__dirname,'..');
const WIDTH = 1672, HEIGHT = 941;
const document = {createElement:() => createCanvas(1,1)};
function cloudSkyline(image) {
      if (!this.cloudSkylines) this.cloudSkylines = new Map();
      if (this.cloudSkylines.has(image)) return this.cloudSkylines.get(image);
      const plate = document.createElement('canvas');
      plate.width = WIDTH; plate.height = HEIGHT;
      const c = plate.getContext('2d', {willReadFrequently:true});
      c.drawImage(image,0,0,WIDTH,HEIGHT);
      const pixels = c.getImageData(0,0,WIDTH,HEIGHT).data;
      // Refine the astronomical guide against the actual photographic edge.
      // Each column participates in one continuous path, avoiding isolated rock details.
      const radius = 24, rows = radius * 2 + 1;
      const guide = Array.from({length:WIDTH},(_,x) => Math.round(this.skylineY(x)));
      const back = new Int16Array(WIDTH * rows);
      let previous = new Float64Array(rows);
      for (let x = 0; x < WIDTH; x++) {
        const scores = new Float64Array(rows);
        for (let k = 0; k < rows; k++) {
          const distant = x < 275 || x > 1445;
          if (x < 275 && Math.abs(k-radius) > 5) { scores[k] = -Infinity; continue; }
          const y = guide[x] + k - radius;
          let distance = 0, blueAbove = 0, blueBelow = 0;
          for (let channel = 0; channel < 3; channel++) {
            const above = (pixels[((y-2)*WIDTH+x)*4+channel] + pixels[((y-1)*WIDTH+x)*4+channel]) / 2;
            const below = (pixels[((y+1)*WIDTH+x)*4+channel] + pixels[((y+2)*WIDTH+x)*4+channel]) / 2;
            distance += (above - below) ** 2;
            blueAbove += above * (channel === 2 ? 1 : -.5);
            blueBelow += below * (channel === 2 ? 1 : -.5);
          }
          const evidence = Math.sqrt(distance) + Math.max(0,blueAbove-blueBelow) * .8;
          let best = 0, from = k;
          if (x > 0) {
            best = -Infinity;
            for (let j = 0; j < rows; j++) {
              const step = y - (guide[x-1] + j - radius);
              if (Math.abs(step) > 24) continue;
              const candidate = previous[j] - Math.abs(step) * (distant ? 14 : 3);
              if (candidate > best) { best = candidate; from = j; }
            }
          }
          scores[k] = best + evidence - Math.abs(k-radius) * .65;
          back[x*rows+k] = from;
        }
        previous = scores;
      }
      let k = previous.indexOf(Math.max(...previous));
      const edge = new Float32Array(WIDTH);
      for (let x = WIDTH-1; x >= 0; x--) {
        edge[x] = guide[x] + k - radius + .5;
        k = back[x*rows+k];
      }
      this.cloudSkylines.set(image,edge);
      return edge;
    }
(async () => {
  const scope = {window:{}};
  vm.runInNewContext(fs.readFileSync(path.join(root,'assets/photo-landscape.js'),'utf8')
    .replace('new PhotoLandscape()', 'Object.create(PhotoLandscape.prototype)'),scope);
  const scene = scope.window.photoScene;
  const result = {};
  for (const [name,file] of [['summer','odle-day.webp'],['winter','odle-winter.webp']]) {
    result[name] = Array.from(cloudSkyline.call(scene,await loadImage(path.join(root,'assets/photo',file))));
  }
  fs.writeFileSync(path.join(root,'assets/photo-skyline.js'),
    '/* Photographic sky boundaries in source pixels. Generated by core/scripts/generate-photo-skyline.cjs. */\n' +
    '(function(root){ const profile = '+JSON.stringify(result)+';\n' +
    'if(typeof module !== "undefined") module.exports=profile; else root.PhotoSkyline=profile;\n' +
    '})(typeof window !== "undefined" ? window : globalThis);\n');
})().catch(error => { console.error(error); process.exitCode=1; });
